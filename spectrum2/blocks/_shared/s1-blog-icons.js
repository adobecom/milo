export const ICON_NAMES = Object.freeze(Object.keys(ICONS));

export function icon(doc, name, className = 's2-blog-icon', { meta = true } = {}) {
  const def = ICONS[name];
  if (!def) throw new Error(`spectrum2: s1-blog-icons has no icon "${name}" (${ICON_NAMES.join(', ')})`);
  const svg = doc.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', def.viewBox);
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  if (className) svg.setAttribute('class', `${className} ${className}-${name}`);
  if (meta && def.title) {
    const title = doc.createElementNS(SVG_NS, 'title');
    title.textContent = def.title;
    svg.append(title);
  }
  if (meta && def.desc) {
    const desc = doc.createElementNS(SVG_NS, 'desc');
    desc.textContent = def.desc;
    svg.append(desc);
  }
  def.paths.forEach((d) => {
    const path = doc.createElementNS(SVG_NS, 'path');
    path.setAttribute('fill', 'currentColor');
    path.setAttribute('d', d);
    svg.append(path);
  });
  return svg;
}
